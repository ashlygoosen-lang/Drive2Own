export interface AgreementInput {
  ownerName: string; driverName: string; vehicle: string; plate: string; platform: string;
  startDate: string; weeks: number; weeklyRate: number; deposit: number;
}

const addDays = (iso: string, n: number) => {
  const d = new Date(`${iso}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
};
const R = (n: number) => `R ${n.toLocaleString('en-ZA')}`;

/** Plain-text vehicle rental agreement. A template only — not legal advice. */
export function buildAgreement(a: AgreementInput): string {
  const end = addDays(a.startDate, a.weeks * 7);
  return `VEHICLE RENTAL AGREEMENT (E-HAILING)

Between ${a.ownerName} ("the Owner") and ${a.driverName} ("the Driver"), arranged through the Drive2Own marketplace.

1. VEHICLE
${a.vehicle}, registration ${a.plate} ("the Vehicle").

2. TERM
The rental starts on ${a.startDate} and runs for ${a.weeks} week(s), ending on ${end}, unless ended earlier under clause 11.

3. PURPOSE
The Driver may use the Vehicle to provide e-hailing services on ${a.platform} and for reasonable private use. The Driver must hold a valid driver's licence and Professional Driving Permit (PrDP) for the whole term and must comply with the platform's terms and all traffic laws.

4. RENT AND DEPOSIT
Rent is ${R(a.weeklyRate)} per week, due on the first day of each rental week. A refundable deposit of ${R(a.deposit)} is due on handover. Payments are recorded in Drive2Own. Drive2Own is not a party to this agreement and does not guarantee payment unless a payment is made through its online payment option.

5. INSURANCE
The Owner confirms the Vehicle is comprehensively insured and that the policy covers e-hailing / commercial passenger use. The Driver must not use the Vehicle in a way that would void that cover.

6. CONDITION AND MAINTENANCE
The Vehicle is handed over roadworthy. The Owner pays for scheduled servicing and wear-and-tear repairs. The Driver pays for fuel, tyre damage caused by misuse, car washes and keeping the Vehicle clean and fit for passengers.

7. FINES AND TOLLS
The Driver is responsible for all traffic fines, tolls and e-tag charges incurred during the term and must pay them promptly.

8. ACCIDENTS AND DAMAGE
The Driver must report any accident, theft or damage to the Owner and the police immediately. The Driver is liable for the insurance excess and for damage caused by negligence or breach of this agreement.

9. USE RESTRICTIONS
The Vehicle may not be sub-let, lent to anyone else, used for any unlawful purpose, or driven under the influence of alcohol or drugs. Only the Driver may drive the Vehicle.

10. RETURN
At the end of the term the Driver returns the Vehicle with its keys and papers, in the same condition as received (fair wear and tear excepted). The deposit is returned within 7 days, less any amounts owed under clauses 7 and 8.

11. TERMINATION
Either party may end this agreement on 7 days' notice. The Owner may end it immediately if rent is more than 7 days overdue or the Driver seriously breaches this agreement.

12. GENERAL
This is a template generated by Drive2Own and is not legal advice. The parties should read it carefully and may agree additional written terms. South African law applies.

By accepting in Drive2Own, each party confirms they have read and agree to this agreement.`;
}
